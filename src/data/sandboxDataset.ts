function makeHistoryItem(params: {
  id: string;
  recordedAtUtc: string;
  kickoffUtc: string;
  leagueId: PredictionHistoryItem['leagueId'];
  matchLabel: string;
  market: string;
  selection: string;
  predictedProb: number;
  oddsAtPrediction: number;
  expectedScore: string;
  confidenceTier: PredictionHistoryItem['confidenceTier'];
  actualOutcome: 0 | 1 | null;
  actualResult: string | null;
}): PredictionHistoryItem {
  const status =
    params.actualOutcome === null ? 'pendiente' : params.actualOutcome === 1 ? 'acertada' : 'fallada';
  const brierScore =
    params.actualOutcome !== null
      ? Number(computeBrierScoreBinary(params.predictedProb, params.actualOutcome).toFixed(4))
      : null;
  const logLoss =
    params.actualOutcome !== null
      ? Number(computeLogLossBinary(params.predictedProb, params.actualOutcome).toFixed(4))
      : null;
  const simulatedRoiUnit =
    params.actualOutcome !== null
      ? Number((params.actualOutcome === 1 ? params.oddsAtPrediction - 1 : -1).toFixed(2))
      : null;

  return {
    id: params.id,
    recordedAtUtc: params.recordedAtUtc,
    kickoffUtc: params.kickoffUtc,
    leagueId: params.leagueId,
    matchLabel: params.matchLabel,
    market: params.market,
    selection: params.selection,
    predictedProb: params.predictedProb,
    oddsAtPrediction: params.oddsAtPrediction,
    expectedScore: params.expectedScore,
    modelVersion: 'ensemble-preview-p2',
    confidenceTier: params.confidenceTier,
    status,
    actualResult: params.actualResult,
    brierScore,
    logLoss,
    simulatedRoiUnit,
    isSynthetic: true,
  };
}

